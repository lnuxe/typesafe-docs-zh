# 术语表（YAML 子集解析，优先 PyYAML，缺失时用自带解析器）
# --------------------------------------------------------------------------


class MiniYaml:
    """极简 YAML 解析器：支持缩进块映射 / 序列、行内 [a, b]、引号标量、# 注释。"""

    def __init__(self, text):
        self.tokens = self._tokenize(text)
        self.i = 0

    @staticmethod
    def _strip_comment(line):
        out = []
        quote = None
        for ch in line:
            if quote:
                out.append(ch)
                if ch == quote:
                    quote = None
                continue
            if ch in "\"'":
                quote = ch
                out.append(ch)
                continue
            if ch == "#" and (not out or out[-1] in " \t"):
                break
            out.append(ch)
        return "".join(out)

    def _tokenize(self, text):
        toks = []
        for raw in text.replace("\t", "    ").splitlines():
            line = self._strip_comment(raw).rstrip()
            if not line.strip():
                continue
            indent = len(line) - len(line.lstrip(" "))
            toks.append([indent, line.strip()])
        return toks

    @staticmethod
    def _scalar(v):
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            return v[1:-1]
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            if not inner:
                return []
            parts, buf, quote = [], [], None
            for ch in inner:
                if quote:
                    buf.append(ch)
                    if ch == quote:
                        quote = None
                    continue
                if ch in "\"'":
                    quote = ch
                    buf.append(ch)
                    continue
                if ch == ",":
                    parts.append("".join(buf))
                    buf = []
                    continue
                buf.append(ch)
            parts.append("".join(buf))
            return [MiniYaml._scalar(p) for p in parts if p.strip()]
        if v in ("null", "~"):
            return None
        if v == "true":
            return True
        if v == "false":
            return False
        return v

    def parse(self):
        if not self.tokens:
            return None
        return self._node(self.tokens[0][0])

    def _node(self, indent):
        if self.i >= len(self.tokens):
            return None
        if self.tokens[self.i][1].startswith("- "):
            return self._seq(indent)
        return self._map(indent)

    def _seq(self, indent):
        items = []
        while self.i < len(self.tokens):
            ind, content = self.tokens[self.i]
            if ind != indent or not content.startswith("- "):
                break
            rest = content[2:].strip()
            if not rest:
                self.i += 1
                items.append(self._node(self.tokens[self.i][0]) if self.i < len(self.tokens) and self.tokens[self.i][0] > indent else None)
                continue
            self.tokens[self.i] = [indent + 2, rest]
            items.append(self._node(indent + 2))
        return items

    def _map(self, indent):
        out = {}
        while self.i < len(self.tokens):
            ind, content = self.tokens[self.i]
            if ind != indent or content.startswith("- "):
                break
            if ":" not in content:
                self.i += 1
                continue
            key, _, val = content.partition(":")
            key = key.strip()
            val = val.strip()
            if val:
                out[key] = self._scalar(val)
                self.i += 1
            else:
                self.i += 1
                if self.i < len(self.tokens) and self.tokens[self.i][0] > indent:
                    out[key] = self._node(self.tokens[self.i][0])
                else:
                    out[key] = None
        return out


def load_glossary(path):
    if not path.exists():
        return None, "missing"
    text = path.read_text(encoding="utf-8")
    try:
        import yaml  # type: ignore

        return yaml.safe_load(text), "pyyaml"
    except Exception:
        pass
    try:
        return MiniYaml(text).parse(), "builtin"
    except Exception as exc:  # pragma: no cover
        return None, "error: %s" % exc



def print_report(report, max_list):
    c = report["checks"]
    cov = c["coverage"]
    out = []
    out.append("TypeSafe 文档中文化审计")
    out.append("=" * 60)
    out.append("纳入统计的 Markdown 文件：%d（另有自动生成 %d 个、仓库文档 %d 个，不计入）" % (
        cov["files_in_scope"], cov["files_by_category"].get("generated", 0),
        cov["files_by_category"].get("meta", 0)))
    out.append("分类：已翻译 %d / 部分翻译 %d / 未翻译 %d / 索引页 %d" % (
        cov["files_by_category"].get("translated", 0),
        cov["files_by_category"].get("partial", 0),
        cov["files_by_category"].get("untranslated", 0),
        cov["files_by_category"].get("index", 0),
    ))
    out.append("文件覆盖率（已翻译/纳入范围）：%.1f%%" % (cov["file_coverage"] * 100))
    out.append("词数覆盖率（已翻译+部分/总计）：%.1f%%  (%d / %d 词)" % (
        cov["word_coverage"] * 100, cov["prose_words_by_category"].get("translated", 0)
        + cov["prose_words_by_category"].get("partial", 0), cov["prose_words_total"]))

    out.append("")
    out.append("-- 未翻译文件（按正文字数降序，最多 %d 条）%s" % (max_list, "-" * 10))
    untr = sorted([(v["prose_words"], k) for k, v in report["files"].items() if v["category"] == "untranslated"], reverse=True)
    for w, k in untr[:max_list]:
        out.append("   %6d 词  %s" % (w, k))
    if len(untr) > max_list:
        out.append("   ... 其余 %d 个见 JSON 报告" % (len(untr) - max_list))

    part = sorted([(v["prose_words"], k, v["cjk_ratio"]) for k, v in report["files"].items() if v["category"] == "partial"], reverse=True)
    if part:
        out.append("")
        out.append("-- 部分翻译文件 %s" % ("-" * 38))
        for w, k, r in part[:max_list]:
            out.append("   %6d 词  CJK %.0f%%  %s" % (w, r * 100, k))

    mx = c["mixed_language"]
    out.append("")
    out.append("-- 混排残留（中文文件里的英文段落）：%d 处，涉及 %d 个文件 %s" % (
        mx["count"], len(mx["files"]), "-" * 6))
    for m in mx["findings"][:max_list]:
        out.append("   %s:%d  [%s] %s" % (m["path"], m["start_line"], m["kind"], m["text"][:110]))
    if mx["count"] > max_list:
        out.append("   ... 其余 %d 处见 JSON 报告" % (mx["count"] - max_list))

    nav = c["navigation"]
    out.append("")
    out.append("-- 导航覆盖 %s" % ("-" * 46))
    out.append("   docs.json 引用页面：%d 个；死链：%d 个" % (nav["pages"], len(nav["missing"])))
    for m in nav["missing"]:
        out.append("   死链 %s" % m)
    out.append("   导航条目未翻译：%d 个（另有自动生成的 SDK 参考页 %d 个，不在人工翻译范围）" % (
        len(nav["untranslated"]), len(nav["generated"])))
    for u in nav["untranslated"][:max_list]:
        if not u["file"].startswith("sdk/"):
            out.append("   [%s] %s" % (u["category"], u["page"]))
    if nav["labels_untranslated"]:
        out.append("   导航标签仍是英文：%s" % ", ".join(nav["labels_untranslated"]))

    g = c["glossary"]
    out.append("")
    out.append("-- 术语表合规（来源：%s）%s" % (report["glossary_source"], "-" * 20))
    out.append("   词条 %d 个；禁用译法违规 %d 处；未在语料中出现的词条 %d 个" % (
        g["entries"], len(g["violations"]), len(g["missing_zh"])))
    for v in g["violations"][:max_list]:
        out.append("   %s:%d  用了「%s」，应为「%s」" % (v["file"], v["line"], v["found"], v["expected"]))

    st = c["structure"]
    out.append("")
    out.append("-- 结构保真 %s" % ("-" * 46))
    if st["source_dir"]:
        out.append("   与英文原文目录 %s 比对：%d 处差异" % (st["source_dir"], len(st["diffs"])))
    else:
        out.append("   未提供 --source-dir，跳过与英文原文的逐项比对")
    out.append("   与基线 %s 比对：%d 处差异" % (st["baseline"] or "(未提供)", len(st["baseline_diffs"])))
    for d in st["baseline_diffs"][:max_list]:
        out.append("   [%s] %s %s" % (d["severity"], d["path"], d["message"]))
    for d in st["diffs"][:max_list]:
        out.append("   [%s] %s %s" % (d["severity"], d["path"], d["message"]))

    out.append("")
    out.append("=" * 60)
    out.append("结论：%s  (error %d / warning %d)" % (
        "PASS" if report["summary"]["ok"] else "FAIL", report["summary"]["errors"], report["summary"]["warnings"]))
    for e in report["errors"][:max_list]:
        out.append("  ERROR   %s" % e)
    if len(report["errors"]) > max_list:
        out.append("  ... 其余 %d 条 error 见 JSON 报告" % (len(report["errors"]) - max_list))
    print("\n".join(out))


def main(argv=None):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description="TypeSafe 文档中文化审计器")
    ap.add_argument("--root", default=str(here.parent), help="仓库根目录")
    ap.add_argument("--docs", default="docs.json", help="Mintlify 导航配置（相对根目录）")
    ap.add_argument("--glossary", default="tools/glossary.yml", help="术语表路径（相对根目录）")
    ap.add_argument("--source-dir", default=None, help="英文原文目录，用于结构逐项比对")
    ap.add_argument("--baseline", default=None, help="结构基线 JSON，用于检测结构回归")
    ap.add_argument("--write-baseline", default=None, help="把当前结构指纹写入基线 JSON")
    ap.add_argument("--json", dest="json_out", default=None, help="JSON 报告输出路径，- 表示 stdout")
    ap.add_argument("--untranslated-below", type=float, default=0.05, help="CJK 占比低于此值判为未翻译")
    ap.add_argument("--translated-above", type=float, default=0.45, help="CJK 占比高于此值判为已翻译")
    ap.add_argument("--mixed-min-words", type=int, default=6, help="混排检测：正文行判定为英文的最少词数")
    ap.add_argument("--heading-min-words", type=int, default=1, help="混排检测：标题行判定为英文的最少词数")
    ap.add_argument("--min-prose-words", type=int, default=20, help="正文字数低于此值归为索引页")
    ap.add_argument("--max-list", type=int, default=25, help="人类可读摘要中每节最多列出的条目数")
    ap.add_argument("--strict", action="store_true", help="存在 error 时以退出码 1 失败")
    args = ap.parse_args(argv)

    report = audit(args)

    if args.write_baseline:
        snap_files = {}
        for k, v in report["files"].items():
            if v["category"] == "generated":
                # 自动生成内容（sdk/**）由上游重新生成，不纳入结构回归保护。
                continue
            st = dict(v["structure"])
            st["headings"] = [{"level": x["level"]} for x in st.get("headings") or []]
            snap_files[k] = {"category": v["category"], "prose_words": v["prose_words"], "structure": st}
        snap = {
            "schema": report["schema"],
            "note": "结构基线：由 tools/i18n_audit.py --write-baseline 生成，用于检测后续提交的结构回归（围栏代码块内容、链接、图片、MDX 组件、标题层级、锚点、表格）。上游内容真实变化时可重新生成。",
            "files": snap_files,
        }
        Path(args.write_baseline).write_text(
            json.dumps(snap, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        print("已写入基线：%s（%d 个文件）" % (args.write_baseline, len(snap["files"])))

    if args.json_out:
        payload = json.dumps(report, ensure_ascii=False, indent=1)
        if args.json_out == "-":
            print(payload)
        else:
            Path(args.json_out).write_text(payload + "\n", encoding="utf-8")

    if args.json_out != "-":
        print_report(report, args.max_list)

    if args.strict and report["errors"]:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

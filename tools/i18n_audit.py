TICK = "\x60"
FENCE_RE = re.compile(r"^(\s*)(\x60{3,}|~{3,})(.*)$")
CJK_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")
LATIN_WORD_RE = re.compile(r"[A-Za-z][A-Za-z'-]*")
INLINE_CODE_RE = re.compile(r"(\x60+)([^\x60]+?)\1")
IMAGE_RE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
IMG_TAG_RE = re.compile(r"<img\b[^>]*\bsrc=\"([^\"]+)\"", re.I)
LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
HREF_RE = re.compile(r"\bhref=[\"']([^\"']+)[\"']")
AUTOLINK_RE = re.compile(r"<https?://[^>]+>")
HTML_TAG_RE = re.compile(r"</?[A-Za-z][A-Za-z0-9-]*(?:\s[^<>]*)?/?>")
URL_RE = re.compile(r"https?://\S+")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$")
COMPONENT_RE = re.compile(r"<([A-Z][A-Za-z0-9]*)[\s/>]")
ANCHOR_RE = re.compile(r"\{#([A-Za-z0-9_.:-]+)\}")
JS_FUNC_RE = re.compile(r"^(export\s+)?(async\s+)?function\s+[A-Za-z_$]")
JS_EXPORT_RE = re.compile(r"^export\s+(default\s+)?(const|let|var|class)\s")
JSX_OPEN_RE = re.compile(r"^</?[A-Za-z][A-Za-z0-9.-]*")
ATTR_TEXT_RE = re.compile(r'\b(title|description|label|summary|placeholder)\s*=\s*"([^"]*)"')
GENERATED_MARKERS = (
    "auto-generated",
    "automatically generated",
    "此文件由",
    "由工具自动生成",
    "do not edit",
    "generated by",
)

DEFAULT_EXCLUDES = (".git", "node_modules", ".mintlify", "tools", ".github", ".vercel", "dist", "build")
GENERATED_PREFIXES = ("sdk/",)
# 仓库自身的说明文档，不是站点页面：不参与覆盖率统计，混排问题降级为 warning。
META_FILES = ("README.md", "TRANSLATING.md", "CONTRIBUTING.md", "CODE_OF_CONDUCT.md")


def word_count(text):
    """中文按字计，拉丁文按词计。"""
    return len(CJK_RE.findall(text)) + len(LATIN_WORD_RE.findall(text))


def score_text(text):
    """返回 (cjk_char_count, latin_word_count, latin_letter_count)。"""
    cjk = len(CJK_RE.findall(text))
    words = LATIN_WORD_RE.findall(text)
    latin_letters = sum(len(w) for w in words)
    return cjk, len(words), latin_letters


def cjk_ratio(cjk, latin_letters):
    denom = cjk + latin_letters
    if denom == 0:
        return 0.0
    return cjk / denom


# --------------------------------------------------------------------------
# Markdown 分行分类
# --------------------------------------------------------------------------
# kind 取值：
#   frontmatter  文件头 YAML
#   fence        围栏代码块内部
#   fence_marker 围栏标记行本身
#   js           export function / 顶层 JS 区域
#   jsx_tag      JSX 组件标签行
#   jsx_attr     组件属性跨行区域
#   prose        正文（唯一参与中文化统计的行）


def classify_lines(lines):
    out = []
    in_front = False
    front_seen = False
    fence = None
    js_region = False
    tag_region = False

    for idx, raw in enumerate(lines):
        n = idx + 1
        s = raw.strip()

        if in_front:
            if s == "---":
                in_front = False
            out.append((n, raw, "frontmatter"))
            continue
        if idx == 0 and s == "---":
            in_front = True
            front_seen = True
            out.append((n, raw, "frontmatter"))
            continue

        if fence is not None:
            m = FENCE_RE.match(raw)
            if m and m.group(2)[0] == fence[0] and len(m.group(2)) >= fence[1] and m.group(3).strip() == "":
                fence = None
                out.append((n, raw, "fence_marker"))
            else:
                out.append((n, raw, "fence"))
            continue

        m = FENCE_RE.match(raw)
        if m and s:
            fence = (m.group(2)[0], len(m.group(2)))
            out.append((n, raw, "fence_marker"))
            continue

        if js_region:
            if raw and not raw[0].isspace() and s == "}":
                js_region = False
            out.append((n, raw, "js"))
            continue

        if JS_FUNC_RE.match(raw) or JS_EXPORT_RE.match(raw):
            js_region = not (s.endswith("}") and not s.endswith("{"))
            out.append((n, raw, "js"))
            continue

        if tag_region:
            if s.endswith("/>") or (s.endswith(">") and not s.endswith("=>")):
                tag_region = False
            out.append((n, raw, "jsx_attr"))
            continue

        if s.startswith("<") and JSX_OPEN_RE.match(s):
            closes = s.endswith("/>") or (s.endswith(">") and not s.endswith("=>"))
            tag_region = not closes
            out.append((n, raw, "jsx_tag"))
            continue

        out.append((n, raw, "prose"))

    return out


def scrub(line):
    """去掉 markdown / 链接 / 行内代码 / HTML 标记，只留下散文。"""
    t = line.strip()
    t = IMAGE_RE.sub(" ", t)
    t = LINK_RE.sub(lambda m: m.group(1), t)
    t = INLINE_CODE_RE.sub(" ", t)
    t = AUTOLINK_RE.sub(" ", t)
    t = HTML_TAG_RE.sub(" ", t)
    t = URL_RE.sub(" ", t)
    t = HREF_RE.sub(" ", t)
    t = re.sub(r"^#{1,6}\s*", "", t)
    t = re.sub(r"^>\s*", "", t)
    t = re.sub(r"^[-*+]\s+", "", t)
    t = re.sub(r"^\d+[.)]\s+", "", t)
    t = t.replace("|", " ")
    t = re.sub(r"[*_~]+", " ", t)
    t = re.sub(r"\s+", " ", t)
    return t.strip()



def collect_nav_pages(node, out):
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "pages" and isinstance(v, list):
                for item in v:
                    if isinstance(item, str):
                        out.append(item)
                    else:
                        collect_nav_pages(item, out)
            elif isinstance(v, (dict, list)):
                collect_nav_pages(v, out)
    elif isinstance(node, list):
        for item in node:
            collect_nav_pages(item, out)


def collect_nav_labels(node, out):
    if isinstance(node, dict):
        for k, v in node.items():
            if k in ("tab", "group") and isinstance(v, str):
                out.append(v)
            elif isinstance(v, (dict, list)):
                collect_nav_labels(v, out)
    elif isinstance(node, list):
        for item in node:
            collect_nav_labels(item, out)


def resolve_page(root, page):
    for cand in (page + ".md", page + ".mdx", page + "/index.md", page + "/index.mdx"):
        if (root / cand).exists():
            return cand
    return None



def audit(args):
    root = Path(args.root).resolve()
    allow = []
    glossary, glossary_src = load_glossary(root / args.glossary)
    if glossary:
        for item in glossary.get("allow") or []:
            if isinstance(item, dict) and item.get("pattern"):
                try:
                    allow.append(re.compile(item["pattern"]))
                except re.error:
                    pass

    files = []
    for pattern in ("*.md", "*.mdx"):
        for p in sorted(root.rglob(pattern)):
            rel = p.relative_to(root).as_posix()
            if any(part in DEFAULT_EXCLUDES for part in rel.split("/")):
                continue
            files.append((rel, p))
    files = sorted(set(files))

    report = {
        "schema": "typesafe-docs-zh/i18n-audit@1",
        "root": str(root),
        "thresholds": {
            "untranslated_below": args.untranslated_below,
            "translated_above": args.translated_above,
            "mixed_min_words": args.mixed_min_words,
            "heading_min_words": args.heading_min_words,
            "min_prose_words": args.min_prose_words,
        },
        "glossary_source": glossary_src,
        "files": {},
        "checks": {},
        "errors": [],
        "warnings": [],
    }

    for rel, path in files:
        text = path.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        regions = classify_lines(lines)

        prose_units = []
        for n, raw, kind in regions:
            if kind == "frontmatter":
                m = re.match(r"^(title|description)\s*:\s*(.+)$", raw.strip())
                if m:
                    prose_units.append((n, m.group(2), "frontmatter"))
                continue
            if kind == "jsx_tag":
                for am in ATTR_TEXT_RE.finditer(raw):
                    val = scrub(am.group(2))
                    if val:
                        prose_units.append((n, val, "jsx_attr"))
                continue
            if kind != "prose":
                continue
            scrubbed = scrub(raw)
            if scrubbed:
                prose_units.append((n, scrubbed, "prose"))

        prose_text = " ".join(u[1] for u in prose_units)
        cjk, latin_words, latin_letters = score_text(prose_text)
        ratio = cjk_ratio(cjk, latin_letters)
        words = word_count(prose_text)

        raw_body = "\n".join(ln for _, ln, k in regions if k in ("prose", "fence"))
        rcjk, _, rletters = score_text(raw_body)
        raw_ratio = cjk_ratio(rcjk, rletters)

        head = "\n".join(lines[:40]).lower()
        generated = rel.startswith(GENERATED_PREFIXES) or any(m in head for m in GENERATED_MARKERS)

        if generated:
            category = "generated"
        elif rel in META_FILES:
            category = "meta"
        elif words < args.min_prose_words:
            category = "index"
        elif ratio >= args.translated_above:
            category = "translated"
        elif ratio < args.untranslated_below:
            category = "untranslated"
        else:
            category = "partial"

        entry = {
            "category": category,
            "lines": len(lines),
            "prose_words": words,
            "cjk_chars": cjk,
            "latin_words": latin_words,
            "cjk_ratio": round(ratio, 4),
            "raw_cjk_ratio": round(raw_ratio, 4),
            "structure": structure_of(lines, regions),
            "mixed": [],
            "notes": [],
        }
        if category in ("translated", "partial"):
            entry["mixed"] = find_mixed(regions, allow, args.heading_min_words, args.mixed_min_words)
        report["files"][rel] = entry

    # ---------------- 覆盖率 ----------------
    human = [k for k, v in report["files"].items() if v["category"] not in ("generated", "meta")]
    counts = Counter(report["files"][k]["category"] for k in report["files"])
    words_by_cat = Counter()
    for k in report["files"]:
        words_by_cat[report["files"][k]["category"]] += report["files"][k]["prose_words"]
    total_words = sum(words_by_cat.values())
    done_words = words_by_cat["translated"] + words_by_cat["partial"]
    report["checks"]["coverage"] = {
        "files_total": len(report["files"]),
        "files_in_scope": len(human),
        "files_by_category": dict(counts),
        "prose_words_total": total_words,
        "prose_words_by_category": dict(words_by_cat),
        "file_coverage": round(counts.get("translated", 0) / len(human), 4) if human else 0.0,
        "word_coverage": round(done_words / total_words, 4) if total_words else 0.0,
    }

    # ---------------- 混排 ----------------
    mixed = []
    for rel, entry in report["files"].items():
        for f in entry["mixed"]:
            mixed.append(dict(f, path=rel))
    mixed.sort(key=lambda x: (x["path"], x["start_line"]))
    report["checks"]["mixed_language"] = {
        "findings": mixed,
        "count": len(mixed),
        "files": sorted(set(m["path"] for m in mixed)),
    }
    for m in mixed:
        if report["files"][m["path"]]["category"] == "meta":
            report["warnings"].append(
                "混排：仓库文档 %s:%d 含英文行：%s" % (m["path"], m["start_line"], m["text"][:80])
            )
        elif report["files"][m["path"]]["category"] == "translated":
            report["errors"].append(
                "混排：已翻译文件 %s:%d 仍有整段英文：%s" % (m["path"], m["start_line"], m["text"][:80])
            )
        else:
            report["warnings"].append(
                "混排：部分翻译文件 %s:%d 仍有英文段落：%s" % (m["path"], m["start_line"], m["text"][:80])
            )

    # ---------------- 导航 ----------------
    docs_path = root / args.docs
    nav = {"exists": docs_path.exists(), "pages": 0, "missing": [], "untranslated": [], "generated": [], "labels_untranslated": []}
    if docs_path.exists():
        try:
            docs = json.loads(docs_path.read_text(encoding="utf-8"))
        except Exception as exc:
            report["errors"].append("docs.json 不是合法 JSON：%s" % exc)
            docs = None
        if docs is not None:
            pages = []
            collect_nav_pages(docs.get("navigation", {}), pages)
            nav["pages"] = len(pages)
            for page in pages:
                resolved = resolve_page(root, page)
                if not resolved:
                    nav["missing"].append(page)
                    report["errors"].append("导航死链：docs.json 引用了不存在的页面 %s" % page)
                    continue
                cat = report["files"].get(resolved, {}).get("category")
                if cat in ("untranslated", "partial"):
                    nav["untranslated"].append({"page": page, "file": resolved, "category": cat})
                elif cat == "generated":
                    nav["generated"].append(page)
            labels = []
            collect_nav_labels(docs.get("navigation", {}), labels)
            for label in dict.fromkeys(labels):
                if not CJK_RE.search(label) and not any(rx.search(label) for rx in allow):
                    nav["labels_untranslated"].append(label)
            if nav["labels_untranslated"]:
                report["warnings"].append("导航标签未翻译：%s" % ", ".join(nav["labels_untranslated"]))
    else:
        report["errors"].append("找不到 %s" % args.docs)
    report["checks"]["navigation"] = nav

    # ---------------- 术语表 ----------------
    terms = {"entries": 0, "violations": [], "missing_zh": [], "english_in_prose": []}
    if glossary is None:
        report["warnings"].append("未找到术语表 %s" % args.glossary)
    else:
        entries = glossary.get("terms") or []
        terms["entries"] = len(entries)
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            term = entry.get("term") or ""
            zh = entry.get("zh") or ""
            zh_hits = 0
            for rel, data in report["files"].items():
                if data["category"] not in ("translated", "partial"):
                    continue
                path = root / rel
                lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
                regions = classify_lines(lines)
                for n, raw, kind in regions:
                    if kind != "prose":
                        continue
                    s = raw.strip()
                    if any(rx.search(s) for rx in allow):
                        continue
                    if zh and zh in s:
                        zh_hits += 1
                    for bad in entry.get("forbidden") or []:
                        if bad and bad in s:
                            terms["violations"].append(
                                {
                                    "file": rel,
                                    "line": n,
                                    "term": term,
                                    "expected": zh,
                                    "found": bad,
                                    "text": s[:160],
                                }
                            )
                            report["errors"].append(
                                "术语表违规：%s:%d 用了禁用译法「%s」，应为「%s」" % (rel, n, bad, zh)
                            )
            if zh and zh_hits == 0:
                terms["missing_zh"].append({"term": term, "zh": zh})
        terms["violations"].sort(key=lambda x: (x["file"], x["line"]))
        if terms["missing_zh"]:
            report["warnings"].append("术语表条目在语料中未出现：%s" % ", ".join(x["zh"] for x in terms["missing_zh"]))
    report["checks"]["glossary"] = terms

    # ---------------- 结构回归 / 与英文原文比对 ----------------
    struct = {"source_dir": args.source_dir, "baseline": args.baseline, "diffs": [], "baseline_diffs": []}
    if args.source_dir:
        sd = Path(args.source_dir)
        for rel, data in report["files"].items():
            src = sd / rel
            if not src.exists():
                continue
            slines = src.read_text(encoding="utf-8", errors="replace").splitlines()
            sstruct = structure_of(slines, classify_lines(slines))
            for d in compare_structures(sstruct, data["structure"], rel):
                struct["diffs"].append(d)
                if d["severity"] == "error":
                    report["errors"].append("结构丢失：%s %s" % (rel, d["message"]))
                else:
                    report["warnings"].append("结构变化：%s %s" % (rel, d["message"]))
    if args.baseline:
        bp = Path(args.baseline)
        if bp.exists():
            base = json.loads(bp.read_text(encoding="utf-8"))
            for rel, old in (base.get("files") or {}).items():
                cur = report["files"].get(rel)
                if not cur:
                    report["errors"].append("基线文件消失：%s（被删除或改名）" % rel)
                    continue
                rank = {"untranslated": 0, "index": 1, "partial": 2, "translated": 3, "generated": 3, "meta": 3}
                if rank.get(cur["category"], 0) < rank.get(old["category"], 0):
                    msg = "分类回退：%s -> %s" % (old["category"], cur["category"])
                    struct["baseline_diffs"].append({"path": rel, "message": msg, "severity": "error"})
                    report["errors"].append("回归：%s %s" % (rel, msg))
                for d in compare_structures(old.get("structure") or {}, cur["structure"], rel):
                    struct["baseline_diffs"].append(d)
                    if d["severity"] == "error":
                        report["errors"].append("结构回归：%s %s" % (rel, d["message"]))
        else:
            report["warnings"].append("基线文件 %s 不存在，跳过回归比对" % args.baseline)
    report["checks"]["structure"] = struct

    report["summary"] = {
        "errors": len(report["errors"]),
        "warnings": len(report["warnings"]),
        "ok": not report["errors"],
    }
    return report


def compare_structures(base, cur, rel):
    diffs = []

    def err(msg):
        diffs.append({"path": rel, "message": msg, "severity": "error"})

    def warn(msg):
        diffs.append({"path": rel, "message": msg, "severity": "warning"})

    if cur["fence_count"] < base.get("fence_count", 0):
        err("围栏代码块 %d -> %d" % (base.get("fence_count", 0), cur["fence_count"]))
    if base.get("fence_langs") and cur["fence_langs"] != base["fence_langs"]:
        err("代码块语言序列变化 %s -> %s" % (base["fence_langs"], cur["fence_langs"]))
    bsha = base.get("fence_code_sha") or []
    csha = cur.get("fence_code_sha") or []
    for i in range(min(len(bsha), len(csha))):
        if bsha[i] != csha[i]:
            err("第 %d 个代码块的代码内容被改动（只允许翻译注释）" % (i + 1))
    if cur["mermaid_count"] < base.get("mermaid_count", 0):
        err("Mermaid 块 %d -> %d" % (base.get("mermaid_count", 0), cur["mermaid_count"]))
    elif base.get("mermaid_sha") and cur.get("mermaid_sha") != base["mermaid_sha"]:
        err("Mermaid 图内容被改动")
    lost_links = sorted(set(base.get("links") or []) - set(cur["links"]))
    if lost_links:
        err("链接目标丢失：%s" % ", ".join(lost_links[:6]))
    lost_images = sorted(set(base.get("images") or []) - set(cur["images"]))
    if lost_images:
        err("图片丢失：%s" % ", ".join(lost_images[:6]))
    lost_components = sorted(set(base.get("components") or []) - set(cur["components"]))
    if lost_components:
        err("MDX 组件丢失：%s" % ", ".join(lost_components[:6]))
    if cur["heading_count"] < base.get("heading_count", 0):
        err("标题数量 %d -> %d" % (base.get("heading_count", 0), cur["heading_count"]))
    base_levels = [x["level"] for x in (base.get("headings") or [])]
    cur_levels = [x["level"] for x in (cur.get("headings") or [])]
    if base_levels and base_levels != cur_levels:
        err("标题层级序列变化 %s -> %s" % (base_levels, cur_levels))
    if cur["table_count"] < base.get("table_count", 0):
        err("表格数量 %d -> %d" % (base.get("table_count", 0), cur["table_count"]))
    lost_anchors = sorted(set(base.get("anchors") or []) - set(cur["anchors"]))
    if lost_anchors:
        err("锚点丢失：%s" % ", ".join(lost_anchors[:6]))
    for name, count in (base.get("inline_code") or {}).items():
        if cur["inline_code"].get(name, 0) < count:
            warn("行内代码数量下降：%s %d -> %d" % (name, count, cur["inline_code"].get(name, 0)))
    return diffs



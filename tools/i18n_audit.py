#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""TypeSafe 文档中文化审计器（零第三方依赖，仅标准库）。

功能
----
1. 逐文件统计 CJK 占比与词数，分类为 未翻译 / 部分翻译 / 已翻译（阈值可配）；
   自动生成内容（sdk/** 等）单独归类为 generated，不计入人工翻译范围。
2. 混排检测：在中文文件里找出残留的英文段落，输出 文件 + 行号 + 原文。
3. 结构保真：围栏代码块（含逐字节内容指纹）、行内代码、链接目标、图片、
   Mermaid 块、MDX/JSX 组件、标题层级、锚点、表格。
   - 给了 --source-dir（英文原文目录）时逐项比对；
   - 没有英文原文时，退化为启发式检查 + 与 --baseline 快照比对回归。
4. 导航覆盖：docs.json 引用的每个页面必须在磁盘上存在（死链），
   并报告哪些导航条目（tab / group 标签、页面）仍未翻译。
5. 术语表合规：按 tools/glossary.yml 的推荐译法 / 禁用译法检查。

输出
----
人类可读摘要默认打到 stdout；--json PATH 写完整 JSON 报告（供 CI 消费）。
--strict 时任何 error 级问题都会让退出码变成 1。

示例
----
    python tools/i18n_audit.py
    python tools/i18n_audit.py --strict --json i18n-report.json
    python tools/i18n_audit.py --write-baseline tools/structure-baseline.json
    python tools/i18n_audit.py --source-dir ../typesafe-docs
"""


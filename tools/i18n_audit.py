def strip_trailing_comment(line):
    """去掉行尾注释（# 或 //），只保留代码本身。字符串里的 # 处理方式两侧一致，不影响比对。"""
    for marker in ("#", "//"):
        cut = None
        for i in range(1, len(line)):
            if line.startswith(marker, i) and line[i - 1].isspace() and line[:i].strip():
                cut = i
                break
        if cut is not None:
            line = line[:cut].rstrip()
    return line


def code_only_lines(body):
    """丢掉注释后的代码正文，用于区分 代码被改 与 代码注释被翻译。"""
    kept = []
    for ln in body:
        s = ln.strip()
        if s.startswith("#") or s.startswith("//") or s.startswith("--") or s.startswith("<!--"):
            continue
        kept.append(strip_trailing_comment(ln))
    return kept


def mermaid_skeleton(body):
    """Mermaid 的节点 ID 与连线不能动，节点里的可读标签可以翻译：比对时先把引号里的标签抹掉。"""
    text = "\n".join(body)
    text = re.sub(r'"[^"]*"', '""', text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def h(text):
    return sha1(text.encode("utf-8")).hexdigest()[:16]


def structure_of(lines, regions):
    kinds = {n: k for n, _, k in regions}
    body_lines = [ln for n, ln, k in regions if k not in ("fence", "fence_marker")]
    whole = "\n".join(body_lines)
    fence_text = "\n".join(ln for n, ln, k in regions if k != "fence")

    fences = []
    cur = None
    for n, ln, k in regions:
        if k == "fence_marker":
            m = FENCE_RE.match(ln)
            if cur is None and m and ln.strip():
                cur = {"line": n, "lang": m.group(3).strip().split()[0] if m.group(3).strip() else "", "body": []}
            elif cur is not None:
                cur["raw_sha"] = h("\n".join(cur["body"]))
                if cur["lang"].startswith("mermaid"):
                    cur["code_sha"] = h(mermaid_skeleton(cur["body"]))
                else:
                    cur["code_sha"] = h("\n".join(code_only_lines(cur["body"])))
                fences.append(cur)
                cur = None
        elif k == "fence" and cur is not None:
            cur["body"].append(ln)

    inline = Counter(INLINE_CODE_RE.findall(whole))
    inline.pop("", None)
    inline_code = Counter()
    for m in INLINE_CODE_RE.finditer(whole):
        inline_code[m.group(2).strip()] += 1

    links = set()
    for m in LINK_RE.finditer(fence_text):
        links.add(m.group(2))
    for m in HREF_RE.finditer(fence_text):
        links.add(m.group(1))
    images = set(m.group(1) for m in IMAGE_RE.finditer(fence_text))
    images |= set(m.group(1) for m in IMG_TAG_RE.finditer(fence_text))

    headings = []
    for n, ln, k in regions:
        if k != "prose":
            continue
        m = HEADING_RE.match(ln.strip())
        if m:
            headings.append({"line": n, "level": len(m.group(1)), "text": scrub(ln)})

    anchors = set(ANCHOR_RE.findall(fence_text))
    components = sorted(set(COMPONENT_RE.findall(fence_text)))
    tables = sum(1 for n, ln, k in regions if k == "prose" and TABLE_SEP_RE.match(ln))

    mermaid = [f for f in fences if f["lang"].startswith("mermaid")]

    return {
        "fence_count": len(fences),
        "fence_langs": [f["lang"] for f in fences],
        "fence_code_sha": [f.get("code_sha", "") for f in fences],
        "fence_raw_sha": [f.get("raw_sha", "") for f in fences],
        "mermaid_count": len(mermaid),
        "mermaid_sha": [f.get("code_sha", "") for f in mermaid],
        "inline_code": dict(sorted(inline_code.items())),
        "links": sorted(links),
        "images": sorted(images),
        "components": components,
        "headings": [{"level": x["level"], "text": x["text"]} for x in headings],
        "heading_count": len(headings),
        "anchors": sorted(anchors),
        "table_count": tables,
    }



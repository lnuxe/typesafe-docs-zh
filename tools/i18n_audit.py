def find_mixed(regions, allow, heading_min_words, prose_min_words):
    findings = []
    block = []

    def flush():
        if not block:
            return
        findings.append(
            {
                "start_line": block[0]["line"],
                "end_line": block[-1]["line"],
                "kind": block[0]["kind"],
                "words": sum(b["words"] for b in block),
                "text": " / ".join(b["text"] for b in block)[:400],
            }
        )
        block.clear()

    for n, raw, kind in regions:
        if kind == "jsx_tag":
            for am in ATTR_TEXT_RE.finditer(raw):
                text = scrub(am.group(2))
                if not text:
                    continue
                cjk, words, letters = score_text(text)
                if cjk == 0 and words >= prose_min_words and letters >= prose_min_words * 3:
                    block.append({"line": n, "words": words, "text": text[:200], "kind": "jsx_attr"})
            continue
        if kind != "prose":
            flush()
            continue
        s = raw.strip()
        if not s:
            flush()
            continue
        text = scrub(s)
        if not text:
            flush()
            continue
        if any(rx.search(s) or rx.search(text) for rx in allow):
            flush()
            continue
        cjk, words, letters = score_text(text)
        if cjk > 0:
            flush()
            continue
        is_heading = bool(HEADING_RE.match(s))
        limit = heading_min_words if is_heading else prose_min_words
        if words >= limit and letters >= limit * 3:
            block.append({"line": n, "words": words, "text": text[:200], "kind": "heading" if is_heading else "prose"})
        else:
            flush()
    flush()
    return findings


